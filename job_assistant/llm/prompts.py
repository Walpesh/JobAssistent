"""
Промпты генерации сопроводительного письма (ручной UI + пакетный режим).
"""


def build_cover_letter_prompt(
    user_profile: str,
    job_description: str,
    *,
    vacancy_title: str = "",
    company: str = "",
    match_score: float | None = None,
) -> str:
    """
    Промпт для копирайтера.
    В пакетном режиме можно передать title/company/match_score для контекста.
    """
    header_bits = []
    if vacancy_title:
        header_bits.append(f"Название: {vacancy_title}")
    if company:
        header_bits.append(f"Компания: {company}")
    if match_score is not None:
        header_bits.append(f"Предварительный match_score: {match_score:.0f}%")
    header = "\n".join(header_bits)

    job_block = job_description
    if header:
        job_block = f"{header}\n\n{job_description}"

    return f"""
Ты — профессиональный карьерный консультант и копирайтер. Твоя единственная задача — составить краткую сводку совпадения и убедительное сопроводительное письмо для отклика.

<my_profile>
{user_profile}
</my_profile>

<job_posting>
{job_block}
</job_posting>

### ЖЁСТКИЕ ПРАВИЛА (нарушение = провал):
1. Используй ТОЛЬКО реальные факты из <my_profile>. Ничего не придумывай и не размывай (нельзя писать «помогал преподавателям в университете» — только «производственная практика в ДЮЦ Меридиан, замена преподавателей, проведение занятий по Unity и Blender»).
2. Полностью адаптируй письмо под КОНКРЕТНУЮ вакансию. Выдели 3–5 самых важных требований/ожиданий из описания и покажи, как твой опыт их закрывает. Не натягивай «продажи» или «телемаркетинг», если в вакансии их нет.
3. ЗАПРЕЩЕНО использовать любые штампы и клише, в том числе:
- «С большим энтузиазмом откликаюсь»
- «Прошу рассмотреть мою кандидатуру»
- «Имею богатый опыт»
- «Коммуникабелен, стрессоустойчив»
- «Буду рад внести свой вклад»
- «Готов к профессиональному развитию»
Вместо этого начинай письмо с конкретного факта или прямой связи с задачей вакансии.
4. Стиль: живой, уверенный, деловой, от первого лица. Без воды. 4–5 содержательных абзацев.
5. Объём письма: полноценное, а не отписка. Каждое предложение должно работать на совпадение с вакансией.

### РАСЧЕТ МАТЧА (для внутреннего анализа):
Оцени требования вакансии по шкале 0-1 и примени веса:
- Hard Skills (опыт/инструменты): вес 0.5
- Soft Skills (коммуникация/адаптивность): вес 0.3
- Формальные критерии (график/локация/образование): вес 0.2
Формула: M = (Sum(Оценка * Вес) / Sum(Вес)) * 100%

### Структура ответа (строго соблюдай):
### 📊 Процент совпадения и анализ
[Итоговый % матча + 1-2 предложения обоснования на основе весов выше]

### ✉️ Сопроводительное письмо
[Текст письма]

"""
